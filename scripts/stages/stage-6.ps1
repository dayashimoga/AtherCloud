function Test-Subphase-6-1-1 {
    Write-AetherLog "INFO" "Auditing Subphase 6.1.1: Multi-Architecture Matrix Build Pipeline..."
    $wfPath = Join-Path $Script:RepoRoot ".github/workflows/build-and-release.yml"
    $content = Get-Content $wfPath -Raw
    $targets = @("x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "x86_64-pc-windows-msvc", "x86_64-apple-darwin", "aarch64-apple-darwin")
    foreach ($t in $targets) {
        if (-not ($content -match $t)) { throw "Target $t missing from CI matrix workflow!" }
    }
    Write-AetherLog "SUCCESS" "Multi-architecture compilation matrix verified in GitHub Actions workflow."
    return $true
}

function Test-Subphase-6-1-2 {
    Write-AetherLog "INFO" "Auditing Subphase 6.1.2: FFmpeg, FFprobe & Cloudflared Sidecar Bundling Automation..."
    $ps1Script = Join-Path $Script:RepoRoot "scripts/bundle-sidecars.ps1"
    $shScript = Join-Path $Script:RepoRoot "scripts/bundle-sidecars.sh"

    if (-not (Test-Path $ps1Script)) { throw "scripts/bundle-sidecars.ps1 missing!" }
    if (-not (Test-Path $shScript)) { throw "scripts/bundle-sidecars.sh missing!" }

    $testOutputDir = Join-Path $env:TEMP "aetherstream-sidecars-audit-$(Get-Random)"
    try {
        $res = & $ps1Script -Target "x86_64-pc-windows-msvc" -OutputDir $testOutputDir -DryRun
        $manifestPath = Join-Path $testOutputDir "sidecar-manifest.json"
        if (-not (Test-Path $manifestPath)) { throw "sidecar-manifest.json was not generated by bundler script!" }
        $manifest = Get-Content $manifestPath -Raw | ConvertFrom-Json
        if (-not $manifest.binaries.cloudflared -or -not $manifest.binaries.ffmpeg -or -not $manifest.binaries.ffprobe) {
            throw "Sidecar manifest missing required binaries!"
        }
    } finally {
        if (Test-Path $testOutputDir) { Remove-Item -Recurse -Force $testOutputDir -ErrorAction SilentlyContinue }
    }

    Write-AetherLog "SUCCESS" "Platform FFmpeg, FFprobe and Cloudflared dependency packaging hooks verified."
    return $true
}

function Test-Subphase-6-1-3 {
    Write-AetherLog "INFO" "Auditing Subphase 6.1.3: Binary Optimization, Stripping & Release Profiles..."
    $cargoToml = Join-Path $Script:RepoRoot "Cargo.toml"
    $content = Get-Content $cargoToml -Raw
    if (-not ($content -match 'opt-level = (3|"z")' -and $content -match 'strip = (true|"symbols")')) {
        throw "Cargo release profile missing optimization or strip configuration!"
    }
    if (-not ($content -match 'lto = (true|"fat")' -and $content -match 'codegen-units = 1')) {
        throw "Cargo release profile missing LTO or single codegen-unit optimization!"
    }
    if (-not ($content -match "profile\.release-small")) {
        throw "Cargo release profile missing release-small profile definition!"
    }
    Write-AetherLog "SUCCESS" "Cargo release profile optimization, LTO, and symbol stripping verified."
    return $true
}

function Test-Subphase-6-2-1 {
    Write-AetherLog "INFO" "Auditing Subphase 6.2.1: Tauri Desktop Bundler (.msi, .exe, .deb, .AppImage, .dmg)..."
    $tauriPath = Join-Path $Script:RepoRoot "client/src-tauri/tauri.conf.json"
    if (-not (Test-Path $tauriPath)) { throw "tauri.conf.json missing!" }
    $conf = Get-Content $tauriPath -Raw | ConvertFrom-Json
    if (-not $conf.tauri.bundle.active) {
        throw "Tauri bundle configuration is not active!"
    }
    $targets = $conf.tauri.bundle.targets
    $hasMsi = $targets -contains "msi" -or $targets -eq "all"
    $hasNsis = $targets -contains "nsis" -or $targets -eq "all"
    $hasDeb = $targets -contains "deb" -or $targets -eq "all"
    $hasAppImage = $targets -contains "appimage" -or $targets -eq "all"
    $hasDmg = $targets -contains "dmg" -or $targets -eq "all"
    if (-not ($hasMsi -and $hasNsis -and $hasDeb -and $hasAppImage -and $hasDmg)) {
        throw "Tauri bundle targets missing required desktop formats (msi, nsis, deb, appimage, dmg)!"
    }
    if (-not $conf.tauri.bundle.windows.wix -or -not $conf.tauri.bundle.windows.nsis) {
        throw "Tauri windows configuration missing WiX MSI or NSIS definitions!"
    }
    if (-not $conf.tauri.bundle.deb -or -not $conf.tauri.bundle.appimage) {
        throw "Tauri linux configuration missing deb or appimage definitions!"
    }
    if (-not $conf.tauri.bundle.macOS.minimumSystemVersion) {
        throw "Tauri macOS configuration missing minimumSystemVersion definition!"
    }

    $wfPath = Join-Path $Script:RepoRoot ".github/workflows/build-and-release.yml"
    $wfContent = Get-Content $wfPath -Raw
    if (-not ($wfContent -match "build-desktop-clients")) {
        throw "Desktop client CI bundling job missing in .github/workflows/build-and-release.yml!"
    }
    if (-not ($wfContent -match "msi" -and $wfContent -match "deb" -and $wfContent -match "AppImage" -and $wfContent -match "dmg")) {
        throw "Desktop installer formats (.msi, .deb, .AppImage, .dmg) missing in CI workflow!"
    }

    Write-AetherLog "SUCCESS" "Tauri desktop bundler configuration verified across Windows (.msi/.exe), Linux (.deb/.AppImage), and macOS (.dmg)."
    return $true
}

function Test-Subphase-6-2-2 {
    Write-AetherLog "INFO" "Auditing Subphase 6.2.2: Android CI Packaging (APK & AAB)..."
    $appGradlePath = Join-Path $Script:RepoRoot "client/android/app/build.gradle"
    if (-not (Test-Path $appGradlePath)) { throw "client/android/app/build.gradle missing!" }
    $gradleContent = Get-Content $appGradlePath -Raw
    if (-not ($gradleContent -match "io\.aetherstream\.app")) {
        throw "Android application ID invalid in build.gradle!"
    }
    if (-not ($gradleContent -match "signingConfigs")) {
        throw "Android signingConfigs missing in build.gradle!"
    }

    $ps1Script = Join-Path $Script:RepoRoot "scripts/build-android.ps1"
    $shScript = Join-Path $Script:RepoRoot "scripts/build-android.sh"
    if (-not (Test-Path $ps1Script)) { throw "scripts/build-android.ps1 missing!" }
    if (-not (Test-Path $shScript)) { throw "scripts/build-android.sh missing!" }

    $wfPath = Join-Path $Script:RepoRoot ".github/workflows/build-and-release.yml"
    $content = Get-Content $wfPath -Raw
    if (-not ($content -match "assembleDebug" -and $content -match "assembleRelease" -and $content -match "bundleRelease")) {
        throw "Android Gradle APK and AAB build steps missing in CI workflow!"
    }
    if (-not ($content -match "aetherstream-android-debug-apk" -and $content -match "aetherstream-android-release-aab")) {
        throw "Android APK and AAB artifact upload definitions missing in CI workflow!"
    }

    Write-AetherLog "SUCCESS" "Android debug APK, release APK, and Play Store AAB CI jobs verified."
    return $true
}

