use axum::{
    http::{header, HeaderValue, StatusCode},
    response::{IntoResponse, Response},
    Json,
};
use serde::{Deserialize, Serialize};
use std::path::Path;

/// RFC 7807 Problem Details for HTTP APIs
/// https://datatracker.ietf.org/doc/html/rfc7807
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ProblemDetails {
    /// A URI reference [RFC3986] that identifies the problem type.
    #[serde(rename = "type")]
    pub problem_type: String,

    /// A short, human-readable summary of the problem type.
    pub title: String,

    /// The HTTP status code generated by the origin server for this occurrence of the problem.
    pub status: u16,

    /// A human-readable explanation specific to this occurrence of the problem.
    /// Strictly sanitizes host filesystem paths to prevent information leakage.
    pub detail: String,

    /// Legacy error field for backwards compatibility with legacy UI consumers.
    pub error: String,

    /// A URI reference that identifies the specific occurrence of the problem.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,

    /// Machine-readable error code (extension member).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub code: Option<String>,

    /// Safe relative subpath or resource identifier, omitting host filesystem prefixes.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub invalid_subpath: Option<String>,
}

impl ProblemDetails {
    pub const MIME_TYPE: &'static str = "application/problem+json";

    pub fn new(
        status: StatusCode,
        problem_type: impl Into<String>,
        title: impl Into<String>,
        detail: impl Into<String>,
    ) -> Self {
        let det = detail.into();
        Self {
            problem_type: problem_type.into(),
            title: title.into(),
            status: status.as_u16(),
            detail: det.clone(),
            error: det,
            instance: None,
            code: None,
            invalid_subpath: None,
        }
    }

    pub fn with_instance(mut self, instance: impl Into<String>) -> Self {
        self.instance = Some(instance.into());
        self
    }

    pub fn with_code(mut self, code: impl Into<String>) -> Self {
        self.code = Some(code.into());
        self
    }

    pub fn with_invalid_subpath(mut self, subpath: impl AsRef<Path>) -> Self {
        let safe = Self::sanitize_subpath(subpath.as_ref());
        self.invalid_subpath = Some(safe);
        self
    }

    /// Strips absolute host drive prefixes (e.g. C:\, F:\), Unix roots (/),
    /// Windows network shares (\\server\share), or device paths to prevent internal host enumeration.
    pub fn sanitize_subpath(path: &Path) -> String {
        let mut components = Vec::new();
        for comp in path.components() {
            if let std::path::Component::Normal(c) = comp {
                let s = c.to_string_lossy();
                // Omit any component containing UNC or device references
                if !s.contains(':') && !s.contains('\\') && !s.contains('/') {
                    components.push(s.into_owned());
                }
            }
        }
        if components.is_empty() {
            String::new()
        } else {
            components.join("/")
        }
    }

    pub fn forbidden_subpath(subpath: impl AsRef<Path>, instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/subpath-forbidden",
            "Subpath Whitelist Violation",
            "Requested subpath is not authorized by the virtual mount access whitelist policy.",
        )
        .with_code("SUBPATH_WHITELIST_VIOLATION")
        .with_invalid_subpath(subpath);

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn path_traversal(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/path-traversal",
            "Directory Traversal Violation",
            "Security boundary violation: Directory traversal sequences are strictly prohibited.",
        )
        .with_code("PATH_TRAVERSAL_DETECTED");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn null_byte_injection(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::BAD_REQUEST,
            "https://aetherstream.dev/errors/null-byte-injection",
            "Null Byte Injection Violation",
            "Security boundary violation: Null byte injection detected in path parameter.",
        )
        .with_code("NULL_BYTE_INJECTION");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn symlink_escape(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/symlink-escape",
            "Symlink Sandbox Escape Violation",
            "Security boundary violation: Symbolic link target resolves outside the virtual mount root.",
        )
        .with_code("SYMLINK_ESCAPE_DETECTED");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn unc_device_bypass(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/device-namespace-bypass",
            "Device Namespace Bypass Violation",
            "Security boundary violation: Windows device namespaces and UNC network paths are strictly prohibited.",
        )
        .with_code("DEVICE_NAMESPACE_BYPASS");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn reserved_device_name(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/reserved-device-name",
            "Reserved Device Name Violation",
            "Security boundary violation: DOS legacy reserved device names are strictly prohibited.",
        )
        .with_code("RESERVED_DEVICE_NAME");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn quarantined_path(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::FORBIDDEN,
            "https://aetherstream.dev/errors/path-quarantined",
            "Quarantined System Path Violation",
            "Security boundary violation: Target points to an OS-critical system path and is quarantined.",
        )
        .with_code("PATH_QUARANTINED");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn mount_not_found(mount_id: &str, instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::NOT_FOUND,
            "https://aetherstream.dev/errors/mount-not-found",
            "Mount Not Found",
            format!("Virtual mount '{}' is not registered.", mount_id),
        )
        .with_code("MOUNT_NOT_FOUND");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn resource_not_found(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::NOT_FOUND,
            "https://aetherstream.dev/errors/resource-not-found",
            "Resource Not Found",
            "Requested resource was not found within the virtual mount.",
        )
        .with_code("RESOURCE_NOT_FOUND");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn read_only_mount(mount_id: &str, instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::METHOD_NOT_ALLOWED,
            "https://aetherstream.dev/errors/mount-read-only",
            "Mount Read-Only",
            format!("Virtual mount '{}' is configured with read-only permissions.", mount_id),
        )
        .with_code("MOUNT_READ_ONLY");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn internal_io_error(instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::INTERNAL_SERVER_ERROR,
            "https://aetherstream.dev/errors/internal-io-error",
            "Filesystem I/O Error",
            "An unexpected internal filesystem I/O error occurred.",
        )
        .with_code("INTERNAL_IO_ERROR");

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn unauthorized(title: &str, detail: &str, code: &str, instance: Option<&str>) -> Self {
        let mut problem = Self::new(
            StatusCode::UNAUTHORIZED,
            "https://aetherstream.dev/errors/unauthorized",
            title,
            detail,
        )
        .with_code(code);

        if let Some(inst) = instance {
            problem = problem.with_instance(inst);
        }
        problem
    }

    pub fn from_sandbox_error(err: &crate::security::SandboxError, instance: Option<&str>) -> Self {
        match err {
            crate::security::SandboxError::NullByteInjection(_) => Self::null_byte_injection(instance),
            crate::security::SandboxError::DirectoryTraversal(_) => Self::path_traversal(instance),
            crate::security::SandboxError::SymlinkEscape(_, _) => Self::symlink_escape(instance),
            crate::security::SandboxError::UncDeviceBypass(_) => Self::unc_device_bypass(instance),
            crate::security::SandboxError::ReservedDeviceName(_) => Self::reserved_device_name(instance),
            crate::security::SandboxError::QuarantinedPath(_) => Self::quarantined_path(instance),
            crate::security::SandboxError::SubpathForbidden(p) => Self::forbidden_subpath(p, instance),
            crate::security::SandboxError::NotFound(_) => Self::resource_not_found(instance),
            crate::security::SandboxError::Io(_) => Self::internal_io_error(instance),
        }
    }

    pub fn from_mount_error(err: &crate::storage::MountError, instance: Option<&str>) -> Self {
        match err {
            crate::storage::MountError::MountNotFound(m) => Self::mount_not_found(m, instance),
            crate::storage::MountError::PathTraversalAttempt => Self::path_traversal(instance),
            crate::storage::MountError::SubpathForbidden(p) => Self::forbidden_subpath(p, instance),
            crate::storage::MountError::NotFound(_) => Self::resource_not_found(instance),
            crate::storage::MountError::ReadOnlyMount(m) => Self::read_only_mount(m, instance),
            crate::storage::MountError::QuarantinedPath(_) => Self::quarantined_path(instance),
            crate::storage::MountError::IoError(_) => Self::internal_io_error(instance),
        }
    }
}

impl IntoResponse for ProblemDetails {
    fn into_response(self) -> Response {
        let status = StatusCode::from_u16(self.status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
        let mut response = Json(self).into_response();
        *response.status_mut() = status;
        response.headers_mut().insert(
            header::CONTENT_TYPE,
            HeaderValue::from_static(Self::MIME_TYPE),
        );
        response
    }
}
